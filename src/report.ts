import { writeFileSync } from "node:fs";
import { mkdirSync } from "node:fs";
import path from "node:path";
import { absolute, type Config } from "./config.ts";
import type { Diagnostic, Report } from "./diagnostics.ts";

export const REPORT_FILENAME = "VALIDATION.md";

const order = (d: Diagnostic): string =>
  `${d.severity === "error" ? "0" : "1"}\u0000${d.uri ?? ""}\u0000${d.code}\u0000${d.line ?? 0}`;

function renderOne(d: Diagnostic): string {
  const where = [d.uri, d.line === undefined ? null : `line ${d.line}`]
    .filter((x) => x !== null && x !== undefined)
    .join(" ");
  const fix = d.fix === undefined ? "" : ` _Fix: ${d.fix}_`;
  return `- \`${d.code}\`${where === "" ? "" : ` ${where}`} — ${d.message}${fix}`;
}

/** A plain generated file, not an `issue` instance (plan §4). */
export function renderReport(report: Report): string {
  const sorted = [...report.diagnostics].sort((a, b) => order(a).localeCompare(order(b)));
  const errors = sorted.filter((d) => d.severity === "error");
  const warnings = sorted.filter((d) => d.severity === "warning");

  const lines = [
    "# Validation",
    "",
    "<!-- This file is generated by loom. Edits are overwritten. -->",
    "",
    report.ok && warnings.length === 0
      ? "No problems found."
      : `${report.errors} error(s), ${report.warnings} warning(s).`,
  ];

  if (errors.length > 0) lines.push("", "## Errors", ...errors.map(renderOne));
  if (warnings.length > 0) lines.push("", "## Warnings", ...warnings.map(renderOne));

  return `${lines.join("\n")}\n`;
}

export function writeReport(cfg: Config, report: Report): string {
  const target = absolute(cfg, `${cfg.designRoot}/${REPORT_FILENAME}`);
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, renderReport(report));
  return `${cfg.designRoot}/${REPORT_FILENAME}`;
}
